import { useEffect, useLayoutEffect, useRef, useState } from "react"
import { api } from "../api"
import { Icon } from "../icons"

const plain = (text) => text.replace(/^#+\s*|\s#+\s/g, " ").replace(/\*\*(.+?)\*\*/g, "$1").replace(/\s+/g, " ").trim()

const seconds = (elapsed) => {
  const ms = parseInt(elapsed, 10)
  return Number.isFinite(ms) ? `${(ms / 1000).toFixed(1)} s` : elapsed
}

const SUGGESTIONS = [
  "Summarise the key obligations of each party.",
  "Is there a termination for convenience clause?",
  "What are the limitation of liability provisions?",
  "Which law governs this agreement, and where are disputes heard?",
]

export default function AskView({ matter, matterId, status, notify, setView, thread, setThread }) {
  const [query, setQuery] = useState("")
  const [busy, setBusy] = useState(false)
  const [selected, setSelected] = useState(null)
  const [activeCite, setActiveCite] = useState(null)
  const endRef = useRef(null)

  useEffect(() => { setSelected(null); setActiveCite(null) }, [matterId])
  useEffect(() => { endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" }) }, [thread.length, busy])

  const ask = async (text) => {
    const q = (text ?? query).trim()
    if (!q || busy) return
    setQuery("")
    setBusy(true)
    const index = thread.length
    setThread(t => [...t, { q, pending: true }])
    let turn
    try {
      const res = await api.search(matterId, q)
      turn = res.error
        ? { q, error: res.error === "no documents in this collection" ? "This matter has no documents yet. Import some first." : res.error }
        : { q, answer: res.answer, chunks: res.chunks || [], elapsed: res.elapsed }
    } catch {
      turn = { q, error: "Couldn’t reach the local engine. Check that Argus is running." }
    }
    setThread(t => t.map((x, i) => (i === index ? turn : x)))
    if (turn.chunks?.length) setSelected(index)
    setBusy(false)
  }

  const showCite = (turnIndex, n) => {
    setSelected(turnIndex)
    setActiveCite(n)
    requestAnimationFrame(() => document.getElementById(`src-${n}`)?.scrollIntoView({ behavior: "smooth", block: "nearest" }))
  }

  const panelTurn = selected != null ? thread[selected] : null
  const empty = thread.length === 0
  const docs = status?.doc_count ?? 0

  return (
    <div className={`ask ${panelTurn?.chunks?.length ? "ask--with-panel" : ""}`}>
      <div className="ask__thread">
        <div className="ask__scroll scroll">
          {empty ? (
            <div className="hero">
              <h1 className="hero__title">What would you like to know about {matter.name}?</h1>
              <p className="hero__sub">
                Ask in plain English. Every answer cites the passages it came from, so you can check it against the source.
              </p>
              <div className="hero__composer">
                <Composer value={query} onChange={setQuery} onSubmit={() => ask()} busy={busy} autoFocus />
              </div>
              {docs > 0 ? (
                <div className="suggestions">
                  {SUGGESTIONS.map(s => (
                    <button key={s} className="suggestion" onClick={() => ask(s)}>{s}</button>
                  ))}
                </div>
              ) : (
                <div className="hero__empty">
                  This matter has no documents yet.
                  <div><button className="btn btn--primary btn--sm" onClick={() => setView("import")}><Icon.Upload size={15} /> Import documents</button></div>
                </div>
              )}
            </div>
          ) : (
            <div className="thread">
              {thread.map((t, i) => (
                <Turn
                  key={i}
                  turn={t}
                  selected={selected === i}
                  activeCite={selected === i ? activeCite : null}
                  onCite={(n) => showCite(i, n)}
                  onToggleSources={() => { setSelected(selected === i ? null : i); setActiveCite(null) }}
                  notify={notify}
                />
              ))}
              <div ref={endRef} />
            </div>
          )}
        </div>

        {!empty && (
          <div className="composer-wrap">
            <Composer value={query} onChange={setQuery} onSubmit={() => ask()} busy={busy} autoFocus />
            <p className="composer__hint">Answers are generated by a local model and can be wrong. Always check the cited sources.</p>
          </div>
        )}
      </div>

      {panelTurn?.chunks?.length > 0 && (
        <SourcesPanel
          turn={panelTurn}
          activeCite={activeCite}
          onClose={() => { setSelected(null); setActiveCite(null) }}
          onSave={async (chunk) => {
            const r = await api.save(matterId, chunk, panelTurn.q)
            notify(r.error ? r.error : "Saved passage", r.error ? "error" : "success")
          }}
        />
      )}
    </div>
  )
}

function Composer({ value, onChange, onSubmit, busy, autoFocus }) {
  const ref = useRef(null)
  useLayoutEffect(() => {
    const el = ref.current
    if (!el) return
    el.style.height = "auto"
    el.style.height = `${Math.min(el.scrollHeight, 200)}px`
  }, [value])

  return (
    <form className="composer" onSubmit={(e) => { e.preventDefault(); onSubmit() }}>
      <textarea
        ref={ref}
        className="composer__input"
        rows={1}
        value={value}
        autoFocus={autoFocus}
        placeholder="Ask a question about this matter…"
        aria-label="Question"
        onChange={(e) => onChange(e.target.value)}
        onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); onSubmit() } }}
      />
      <button className="composer__send" type="submit" disabled={!value.trim() || busy} aria-label="Ask">
        {busy ? <span className="spinner" /> : <Icon.Send size={17} />}
      </button>
    </form>
  )
}

function Turn({ turn, selected, activeCite, onCite, onToggleSources, notify }) {
  if (turn.pending) {
    return (
      <article className="turn">
        <h2 className="turn__q">{turn.q}</h2>
        <div className="thinking" aria-live="polite">
          <span className="thinking__label">Searching documents and drafting an answer…</span>
          <div className="shimmer" style={{ width: "92%" }} />
          <div className="shimmer" style={{ width: "84%" }} />
          <div className="shimmer" style={{ width: "58%" }} />
        </div>
      </article>
    )
  }

  const copy = async () => {
    await navigator.clipboard.writeText(turn.answer)
    notify("Answer copied")
  }

  return (
    <article className="turn">
      <h2 className="turn__q">{turn.q}</h2>
      {turn.error ? (
        <p className="turn__a turn__a--error">{turn.error}</p>
      ) : (
        <>
          <p className="turn__a"><Cited text={turn.answer} max={turn.chunks.length} active={activeCite} onCite={onCite} /></p>
          <div className="turn__meta">
            {turn.chunks.length > 0 && (
              <button className={`btn btn--ghost btn--sm ${selected ? "btn--on" : ""}`} onClick={onToggleSources}>
                <Icon.Docs size={15} /> {turn.chunks.length} source{turn.chunks.length === 1 ? "" : "s"}
              </button>
            )}
            <button className="btn btn--ghost btn--sm" onClick={copy}><Icon.Copy size={15} /> Copy</button>
            {turn.elapsed && <><span className="sep">·</span><span>{seconds(turn.elapsed)}</span></>}
          </div>
        </>
      )}
    </article>
  )
}

function Cited({ text, max, active, onCite }) {
  return text.split(/(\[\d+\])/g).map((part, i) => {
    const m = part.match(/^\[(\d+)\]$/)
    const n = m && Number(m[1])
    if (!n || n > max) return part
    return (
      <button key={i} className={`cite ${active === n ? "cite--active" : ""}`} onClick={() => onCite(n)} title={`Show source ${n}`}>
        {n}
      </button>
    )
  })
}

function SourcesPanel({ turn, activeCite, onClose, onSave }) {
  const [open, setOpen] = useState({})
  return (
    <aside className="panel" aria-label="Sources">
      <div className="panel__head">
        <span className="panel__title">Sources</span>
        <span className="panel__count">{turn.chunks.length}</span>
        <button className="icon-btn" onClick={onClose} aria-label="Close sources"><Icon.X size={17} /></button>
      </div>
      <div className="panel__body scroll">
        {turn.chunks.map((c, i) => {
          const n = i + 1
          return (
            <div key={i} id={`src-${n}`} className={`source ${activeCite === n ? "source--active" : ""} ${open[i] ? "source--open" : ""}`}>
              <div className="source__head">
                <span className="source__num">{n}</span>
                <span className="source__name" title={`${c.source} · similarity ${(c.similarity || 0).toFixed(2)}`}>{c.source}</span>
              </div>
              <p className="source__text">{plain(c.text)}</p>
              <div className="source__foot">
                <button className="btn btn--ghost btn--sm" onClick={() => setOpen(o => ({ ...o, [i]: !o[i] }))}>
                  {open[i] ? "Show less" : "Show full passage"}
                </button>
                <button className="btn btn--ghost btn--sm" onClick={() => onSave(c)}><Icon.Bookmark size={15} /> Save</button>
              </div>
            </div>
          )
        })}
      </div>
    </aside>
  )
}
